// The product grader.
//
// One product now. `campaign-ledger`, `campaign-service` and `retrieval-app` are deleted: three
// headless Node products, thirteen steps, ~250 lines of hand-written graders here, and between
// them they could never fill `fmt`, `lint`, `typecheck` or `coverage`, never exercise a UI, and
// never make an E2E defect possible at all. `calculator` is React + TypeScript with a real
// toolchain, so detection fills six verbs (`.claude/harness/lib/toolchain.mjs:37-61`) and the delivery
// the harness is measured on crosses a service/UI boundary.
//
// Transport only runs beside untrusted product code; private expectations remain in this process.
// A product can return incorrect output, but cannot rewrite the parent's assertion functions.
export function calcCalls(source, calls) {
  const bridge = `import * as api from './src/calc.ts';
    let input=''; for await(const part of process.stdin) input+=part;
    const results=[];
    for(const call of JSON.parse(input)) {
      try { const value=await api[call.fn](...call.args);
        results.push({ok:true,value:Number.isNaN(value)?'NaN':value});
      } catch(error){results.push({ok:false,error:String(error && error.message || error)});}
    } console.log(JSON.stringify(results));`;
  const r = execNode(source.work, ['--no-warnings', '--input-type=module', '-e', bridge], { input: JSON.stringify(calls) });
  if (r.status !== 0) throw new Error(`calculator runtime failed: ${r.error?.message ?? r.stderr}`);
  return JSON.parse(r.stdout.trim());
}

// The accessible contract the spec states, so the grader addresses the UI the way a user does
// and not the way the agent happened to build it.
const UI = {
  left: 'Left operand', right: 'Right operand', operation: 'Operation', equals: '=', result: 'status',
};

// A calculator whose UI does its own arithmetic passes every DOM test and still has the defect the
// second intent exists to prevent. So the UI is graded twice: once against the real service, and
// once against a service replaced by constants. A component that reimplements `add` shows 5 when
// the substituted service says 111, and that is the only way to tell from outside.
const SENTINEL = { add: 111, subtract: 222, multiply: 333, divide: 444 };

function uiCases(level, sentinel) {
  const v = (real, op) => (sentinel ? SENTINEL[op] : real);
  const cases = [
    { a: '2', b: '3', op: 'add', expect: String(v(5, 'add')) },
    { a: '2', b: '3', op: 'subtract', expect: String(v(-1, 'subtract')) },
  ];
  if (level >= 3) cases.push(
    { a: '4', b: '3', op: 'multiply', expect: String(v(12, 'multiply')) },
    { a: '9', b: '3', op: 'divide', expect: String(v(3, 'divide')) },
  );
  return cases;
}

function graderSpec(level, sentinel) {
  const cases = uiCases(level, sentinel);
  // The divide-by-zero message is the service's, so it is only asserted against the real service.
  const zero = !sentinel && level >= 3;
  return `import { render, screen, fireEvent } from '@testing-library/react';
import { App } from './App';

const compute = (a, b, op) => {
  render(<App />);
  fireEvent.change(screen.getByLabelText(${JSON.stringify(UI.left)}), { target: { value: a } });
  fireEvent.change(screen.getByLabelText(${JSON.stringify(UI.right)}), { target: { value: b } });
  fireEvent.change(screen.getByLabelText(${JSON.stringify(UI.operation)}), { target: { value: op } });
  fireEvent.click(screen.getByRole('button', { name: ${JSON.stringify(UI.equals)} }));
  return String(screen.getByRole(${JSON.stringify(UI.result)}).textContent ?? '');
};

${cases.map((c, i) => `test('case ${i}: ${c.a} ${c.op} ${c.b}', () => {
  expect(compute(${JSON.stringify(c.a)}, ${JSON.stringify(c.b)}, ${JSON.stringify(c.op)})).toContain(${JSON.stringify(c.expect)});
});`).join('\n\n')}
${zero ? `
test('a zero divisor is refused in words, not as Infinity or NaN', () => {
  const shown = compute('1', '0', 'divide');
  expect(shown).toMatch(/divi/i);
  expect(shown).not.toMatch(/Infinity|NaN/);
});` : ''}
`;
}

const SENTINEL_SERVICE = `export function add() { return ${SENTINEL.add}; }
export function subtract() { return ${SENTINEL.subtract}; }
export function multiply() { return ${SENTINEL.multiply}; }
export function divide() { return ${SENTINEL.divide}; }
`;

// Runs in a snapshot, so neither the grader test nor the substituted service ever reaches the
// candidate diff, the baseline or the scope check.
function runUiGrader(s, level, { sentinel = false } = {}) {
  const source = runtimeSnapshot(s);
  try {
    if (sentinel) writeFileSync(path.join(source.work, 'src/calc.ts'), SENTINEL_SERVICE);
    const spec = path.join(source.work, 'src/harness-grader.test.tsx');
    writeFileSync(spec, graderSpec(level, sentinel));
    const r = spawnSync('npx', ['vitest', 'run', 'src/harness-grader.test.tsx'],
      { cwd: source.work, encoding: 'utf8', timeout: 180000, env: productEnv() });
    if (r.status !== 0) {
      const why = `${r.stdout ?? ''}${r.stderr ?? ''}`.split('\n').filter((l) => /(AssertionError|Unable to find|expected|Error:|FAIL)/.test(l)).slice(0, 6).join(' | ');
      throw new Error(`the form ${sentinel ? 'does not use the arithmetic service' : 'does not compute what the service returns'}: ${why || 'vitest exited ' + r.status}`);
    }
    return uiCases(level, sentinel).length + (!sentinel && level >= 3 ? 1 : 0);
  } finally { source.dispose(); }
}

export function verifyCalculator(s, level) {
  const source = runtimeSnapshot(s);
  let results;
  try {
    const calls = [
      { fn: 'add', args: [2, 3] }, { fn: 'add', args: [-4, 1.5] },
      { fn: 'subtract', args: [2, 3] }, { fn: 'subtract', args: [10, 10] },
      { fn: 'add', args: [1, Number.NaN] }, { fn: 'add', args: [Number.POSITIVE_INFINITY, 1] },
      { fn: 'subtract', args: ['2', 3] }, { fn: 'add', args: [1] },
    ];
    if (level >= 3) calls.push(
      { fn: 'multiply', args: [4, 3] }, { fn: 'multiply', args: [-2, 2.5] },
      { fn: 'divide', args: [9, 3] }, { fn: 'divide', args: [1, 0] },
      { fn: 'divide', args: [0, 5] }, { fn: 'multiply', args: [2, Number.NaN] },
    );
    results = calcCalls(source, calls);
    assert.equal(results.length, calls.length);
  } finally { source.dispose(); }

  const r = results;
  assert.deepEqual(r.slice(0, 4).map((x) => x.value), [5, -2.5, -1, 0], 'add and subtract over finite numbers');
  for (const i of [4, 5, 6, 7]) {
    assert.equal(r[i].ok, false, `invalid argument case ${i} must throw, got ${JSON.stringify(r[i].value)}`);
    assert.ok(/\S/.test(r[i].error ?? ''), `invalid argument case ${i} must throw with a message`);
  }
  if (level >= 3) {
    assert.deepEqual(r.slice(8, 11).map((x) => x.value), [12, -5, 3], 'multiply and divide');
    assert.equal(r[11].ok, false, 'a zero divisor must be refused');
    assert.match(r[11].error ?? '', /divi|zero/i, 'the zero-divisor error must name what went wrong');
    assert.equal(r[12].value, 0, 'zero divided by a number is zero, not an error');
    assert.equal(r[13].ok, false, 'multiply validates its arguments too');
  }

  let cases = r.length;
  if (level >= 2) {
    cases += runUiGrader(s, level);
    cases += runUiGrader(s, level, { sentinel: true });
  }
  return { name: `calculator-level-${level}`, pass: true, cases };
}
