#!/usr/bin/env node
// G21. The golden tasks, emitted in the layout `claude plugin eval` reads.
//
// `evals/tasks.json` stays the source. It has to: four of its assertion kinds have no counterpart
// in the free grader set — `fixture_tests_pass` runs a fixture's own suite, `harness_stage_passes`
// runs a stage, `under_baseline` compares against a recorded figure, and the campaigns are
// multi-step runs with approvals between them. `run.mjs` keeps those.
//
// What the generator emits is the half that maps cleanly: a prompt, and one grader per assertion
// that `claude plugin eval` can score for free. Running both layouts over the same tasks is the
// point — two independent graders of one behaviour disagreeing is a finding, and a task that only
// one of them can express is stated as such rather than approximated in the other.
//
//   node evals/generate-cases.mjs            # write evals/cases/
//   node evals/generate-cases.mjs --check    # fail if what is on disk is not what this produces
//
// Generated, never hand-edited: two places stating one task is two tasks that drift.

import { mkdirSync, readFileSync, writeFileSync, rmSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const CASES_DIR = path.join(HERE, 'cases');
const HEADER = 'Generated by evals/generate-cases.mjs from evals/tasks.json. Do not edit by hand.';

// The assertion kinds a free grader can express, and the grader each becomes. Anything absent from
// this table stays with `run.mjs` — deliberately, and reported by `--check`.
const GRADERS = {
  transcript_matches: (value) => ({ type: 'regex', pattern: String(value), body: 'The transcript matches the pattern.' }),
  file_exists: (value) => ({ type: 'file_exists', path: String(value), body: 'The run created the file.' }),
  transcript_order: (value) => ({ type: 'tool_order', before: String(value[0]), after: String(value[1]), body: 'The first happened before the second.' }),
};

// Kinds that need something only `run.mjs` has: a fixture's suite, a harness stage, a recorded
// baseline, or a file comparison against the staged tree.
// `transcript_not_matches` is here for a reason the CLI told us: the free `regex` grader has no
// negation, and expressing "this must not appear" as an `llm` grader would pay a model to answer
// a question a substring search already answers. A negative assertion stays with `run.mjs`.
export const RUNNER_ONLY = ['fixture_tests_pass', 'harness_stage_passes', 'under_baseline',
  'files_unchanged', 'workdir_unchanged', 'file_matches', 'file_not_matches', 'transcript_not_matches'];

const slug = (id) => String(id).replace(/[^a-z0-9-]+/gi, '-').toLowerCase();

export function caseFor(task) {
  const assertions = task.assert ?? [];
  const graders = [];
  const unsupported = [];
  for (const assertion of assertions) {
    for (const [kind, value] of Object.entries(assertion)) {
      if (GRADERS[kind]) graders.push({ kind, ...GRADERS[kind](value) });
      else unsupported.push(kind);
    }
  }
  // A case with no free grader would be a case that always scores 1: it asserts nothing, and a
  // grader-less pass is worse than no case at all.
  if (!graders.length) return { id: task.id, skipped: true, unsupported };

  // File tools only when a grader needs the run to have written something. The CLI warns when a
  // `file_exists` grader cannot pass with the granted tools, and it is right to.
  const needsWrite = graders.some((g) => g.type === 'file_exists');
  const tools = ['Read', 'Glob', 'Grep', 'Skill', ...(needsWrite ? ['Write', 'Edit'] : [])];
  return {
    id: task.id,
    dir: slug(task.id),
    unsupported,
    prompt: [
      '---',
      `# ${HEADER}`,
      'max_turns: 12',
      `allowed_tools: [${tools.join(', ')}]`,
      ...(task.repeats ? [`runs: ${task.repeats}`] : []),
      '---',
      '',
      task.prompt.trim(),
      '',
    ].join('\n'),
    graders: graders.map((g, i) => ({
      name: `${g.kind.replace(/_/g, '-')}-${i + 1}`,
      text: [
        '---',
        `# ${HEADER}`,
        `type: ${g.type}`,
        'weight: 1',
        ...(g.pattern !== undefined ? [`pattern: ${JSON.stringify(g.pattern)}`] : []),
        ...(g.path !== undefined ? [`path: ${JSON.stringify(g.path)}`] : []),
        ...(g.before !== undefined ? [`before: ${JSON.stringify(g.before)}`] : []),
        ...(g.after !== undefined ? [`after: ${JSON.stringify(g.after)}`] : []),
        '---',
        '',
        g.body,
        '',
      ].join('\n'),
    })),
  };
}

export function generate(tasks) {
  return tasks.map(caseFor);
}

export function write(cases, dir = CASES_DIR) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const written = [];
  for (const c of cases) {
    if (c.skipped) continue;
    const caseDir = path.join(dir, c.dir);
    mkdirSync(path.join(caseDir, 'graders'), { recursive: true });
    writeFileSync(path.join(caseDir, 'prompt.md'), c.prompt);
    for (const g of c.graders) writeFileSync(path.join(caseDir, 'graders', `${g.name}.md`), g.text);
    written.push(c.dir);
  }
  return written;
}

// What is on disk, for `--check`: the generator is only a source of truth if nothing edits its
// output behind it.
export function onDisk(dir = CASES_DIR) {
  if (!existsSync(dir)) return {};
  const out = {};
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const caseDir = path.join(dir, entry.name);
    // A directory with a prompt is a case; anything else here is the CLI's own output — it writes
    // `results/` beside the cases it just ran — and comparing that against the generator would
    // report drift every time the suite is scored.
    if (!existsSync(path.join(caseDir, 'prompt.md'))) continue;
    out[entry.name] = { prompt: readFileSync(path.join(caseDir, 'prompt.md'), 'utf8'), graders: {} };
    const gradersDir = path.join(caseDir, 'graders');
    if (!existsSync(gradersDir)) continue;
    for (const g of readdirSync(gradersDir)) out[entry.name].graders[g] = readFileSync(path.join(gradersDir, g), 'utf8');
  }
  return out;
}

// Compared by content, in a fixed order. `onDisk` reads in directory order and `expected` builds
// in task order, and a stringify of two objects with the same entries in different orders is two
// different strings — which reported drift on a tree that was byte-identical.
export const canonical = (tree) => JSON.stringify(tree, Object.keys(tree ?? {}).flatMap((k) =>
  [k, ...Object.keys(tree[k] ?? {}), ...Object.keys(tree[k]?.graders ?? {})]).sort());

export function expected(cases) {
  const out = {};
  for (const c of cases) {
    if (c.skipped) continue;
    out[c.dir] = { prompt: c.prompt, graders: Object.fromEntries(c.graders.map((g) => [`${g.name}.md`, g.text])) };
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { loadTasks } = await import('./run.mjs');
  const tasks = loadTasks();
  const cases = generate(tasks);
  const skipped = cases.filter((c) => c.skipped);

  if (process.argv.includes('--check')) {
    const same = canonical(onDisk()) === canonical(expected(cases));
    if (!same) {
      console.error('evals/cases/ is not what evals/tasks.json generates — run: node evals/generate-cases.mjs');
      process.exit(1);
    }
    console.log(`evals/cases/ matches evals/tasks.json (${cases.length - skipped.length} cases)`);
    process.exit(0);
  }

  const written = write(cases);
  console.log(`wrote ${written.length} case(s) to ${path.relative(process.cwd(), CASES_DIR)}`);
  for (const c of skipped) console.log(`  run.mjs only: ${c.id} (${[...new Set(c.unsupported)].join(', ')})`);
  const partial = cases.filter((c) => !c.skipped && c.unsupported.length);
  for (const c of partial) console.log(`  partly graded here: ${c.id} — ${[...new Set(c.unsupported)].join(', ')} stay with run.mjs`);
}
