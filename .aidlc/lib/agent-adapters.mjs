function markdown(digest, title, body) {
  return `<!-- ${GENERATED} ${digest}; do not edit -->\n${title ? `# ${title}\n\n` : ''}${body.trim()}\n`;
}

function jsonGenerated(digest, value) {
  return `${JSON.stringify({ _generated: `${GENERATED} ${digest}; do not edit`, ...value }, null, 2)}\n`;
}

